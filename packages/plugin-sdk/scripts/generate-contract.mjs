// Writes lib/contract.ts: every type alias exported by contract-source.ts,
// expanded into a plain type, so the published SDK carries Ajour's contract
// without zod or @ajour/shared. Run it after changing a shared schema:
//
//   corepack pnpm --filter @ajour/plugin-sdk generate
//
// With --check, it writes nothing and exits 1 when lib/contract.ts is stale.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";
import ts from "typescript";

const packageRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const sourcePath = path.join(packageRoot, "scripts", "contract-source.ts");
const outputPath = path.join(packageRoot, "lib", "contract.ts");

const HEADER = `// Generated by scripts/generate-contract.mjs from Ajour's shared schemas.
// Do not edit: change the schema, then run \`pnpm generate\`.
`;

function generate() {
  const program = ts.createProgram([sourcePath], {
    strict: true,
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    allowImportingTsExtensions: true,
    noEmit: true,
    skipLibCheck: true,
    types: [],
  });
  const problems = ts.getPreEmitDiagnostics(program);
  if (problems.length > 0) {
    throw new Error(
      ts.formatDiagnostics(problems, {
        getCanonicalFileName: (name) => name,
        getCurrentDirectory: () => packageRoot,
        getNewLine: () => "\n",
      }),
    );
  }
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(sourcePath);
  const moduleSymbol = checker.getSymbolAtLocation(source);
  const blocks = [];
  for (const symbol of checker.getExportsOfModule(moduleSymbol)) {
    const declaration = symbol.declarations?.[0];
    if (!declaration || !ts.isTypeAliasDeclaration(declaration)) continue;
    const text = checker.typeToString(
      checker.getTypeAtLocation(declaration.type),
      undefined,
      ts.TypeFormatFlags.NoTruncation |
        ts.TypeFormatFlags.InTypeAlias |
        ts.TypeFormatFlags.MultilineObjectLiterals,
    );
    if (/\bZod|\bimport\(/.test(text)) {
      throw new Error(`${symbol.name} still names a schema type: ${text}`);
    }
    const docs = ts.displayPartsToString(
      symbol.getDocumentationComment(checker),
    );
    blocks.push(
      `${docs ? `/** ${docs} */\n` : ""}export type ${symbol.name} = ${text};`,
    );
  }
  return `${HEADER}\n${blocks.join("\n\n")}\n`;
}

const config = (await prettier.resolveConfig(outputPath)) ?? {};
const generated = await prettier.format(generate(), {
  ...config,
  filepath: outputPath,
});

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current.replaceAll("\r\n", "\n") !== generated) {
    console.error(
      "lib/contract.ts is stale. Run: corepack pnpm --filter @ajour/plugin-sdk generate",
    );
    process.exit(1);
  }
} else {
  await writeFile(outputPath, generated);
}
